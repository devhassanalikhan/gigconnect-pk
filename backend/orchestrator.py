async def _generate_content_async_robust(prompt: str) -> Any:
    """
    Robust asynchronous content generator with fallback models to survive quota/rate limits.
    """
    models_to_try = [GEMINI_MODEL, "gemini-2.5-flash-lite", "gemini-2.0-flash-lite", "gemini-1.5-flash", "gemini-2.5-flash"]
    # De-duplicate while preserving order
    seen = set()
    models_to_try = [x for x in models_to_try if not (x in seen or seen.add(x))]
    
    last_exc = None
    for model_name in models_to_try:
        try:
            m = genai.GenerativeModel(model_name)
            response = await m.generate_content_async(prompt)
            if response and response.text:
                return response
        except Exception as exc:
            print(f"[AI Fallback] Gemini call failed with {model_name}: {exc}. Trying next fallback...")
            last_exc = exc
    if last_exc:
        raise last_exc
    raise RuntimeError("All configured Gemini models failed to generate content.")


