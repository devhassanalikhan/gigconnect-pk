def _haversine(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    """Return distance in km between two coordinates."""
    R = 6371
    dlat = math.radians(lat2 - lat1)
    dlng = math.radians(lng2 - lng1)
    a = (math.sin(dlat / 2) ** 2
         + math.cos(math.radians(lat1)) * math.cos(math.radians(lat2))
         * math.sin(dlng / 2) ** 2)
    return round(R * 2 * math.asin(math.sqrt(a)), 2)


def _trace_entry(agent: str, status: str, **kwargs) -> dict:
    emoji = "⚙️"
    if agent == "LinguisticAgent": emoji = "🗣️"
    elif agent == "GeoAgent": emoji = "📍"
    elif agent == "SchedulingAgent": emoji = "📅"
    elif agent == "BiddingAgent": emoji = "🤝"
    elif agent == "EscrowAgent": emoji = "🔒"
    elif agent == "FollowUpAgent": emoji = "📞"
    elif agent == "System": emoji = "🤖"

    color = "\033[96m"
    if status == "success":   color = "\033[92m"
    elif status == "warning": color = "\033[93m"
    elif status == "error":   color = "\033[91m"

    reset = "\033[0m"
    bold  = "\033[1m"

    msg = kwargs.get("message") or kwargs.get("error") or str(kwargs.get("output", "")) or ""
    if len(msg) > 120:
        msg = msg[:117] + "..."

    print(f"{emoji}  {bold}{color}{agent:<18}{reset} | {color}{status.upper():<8}{reset} | {msg}")

    return {
        "agent":     agent,
        "status":    status,
        "timestamp": dt.utcnow().isoformat() + "Z",
        **kwargs,
    }


def _compute_match_score(provider: dict, budget: float, text_query: str = "") -> float:
    """Production-grade 8-Factor Decision Scoring Engine (MCDA)."""
    # 1. Proximity Score (25% weight)
    dist = provider.get("distance_km", 5.0)
    proximity_score = math.exp(-0.2 * dist)  # Exponential decay curve
    
    # 2. Rating Score (15% weight)
    rating = provider.get("rating", 4.0)
    rating_score = rating / 5.0
    
    # 3. Reliability & On-Time Performance (15% weight)
    reliability_score = provider.get("on_time_score", 0.85)
    
    # 4. Low Cancellation Rate (10% weight)
    cancellation_score = 1.0 - provider.get("cancellation_rate", 0.05)
    
    # 5. Review Recency & Velocity (10% weight)
    recency_score = provider.get("review_recency_score", 0.82)
    
    # 6. Experience Level (10% weight)
    exp = provider.get("experience_years", 3)
    experience_score = min(1.0, exp / 10.0)
    
    # 7. Domain Specialization Match (10% weight)
    specialization_score = 0.5
    specializations = provider.get("specializations", [])
    if specializations and text_query:
        query_lower = text_query.lower()
        matched_specs = [s for s in specializations if s.lower() in query_lower]
        if matched_specs:
            specialization_score = 1.0
        elif any(k in query_lower for k in ["leak", "fitting", "repair", "short", "wiring", "cooling", "gas"]):
            specialization_score = 0.8
            
    # 8. Safety & Trust (5% weight)
    safety_score = 1.0 - provider.get("risk_score", 0.12)
    
    composite = (
        proximity_score      * 0.25 +
        rating_score         * 0.15 +
        reliability_score    * 0.15 +
        cancellation_score   * 0.10 +
        recency_score        * 0.10 +
        experience_score     * 0.10 +
        specialization_score * 0.10 +
        safety_score         * 0.05
    )
    return round(composite, 4)


def _local_heuristic_parse(text: str) -> dict:
    import re
    text_lower = text.lower()

    service_type = "Plumber"
    if any(k in text_lower for k in ["plumber","nalka","pipe","paani","leak","toti"]):
        service_type = "Plumber"
    elif any(k in text_lower for k in ["electrician","bijli","wiring","current","board","short","button"]):
        service_type = "Electrician"
    elif any(k in text_lower for k in ["ac","cooling","thanda","technician","fridge","gas"]):
        service_type = "AC Technician"
    elif any(k in text_lower for k in ["painter","paint","rang","color","wall"]):
        service_type = "Painter"
    elif any(k in text_lower for k in ["tutor","teacher","padhai","ustaad","math","study"]):
        service_type = "Tutor"
    elif any(k in text_lower for k in ["carpenter","barhai","wood","furniture","door","table"]):
        service_type = "Carpenter"

    location = DEFAULT_LOCATION
    for key in LOCAL_GEO_DIRECTORY.keys():
        if key.lower() in text_lower:
            location = key
            break

    if location == DEFAULT_LOCATION:
        loc_match = re.search(r'\b([a-z]-\d{1,2})\b', text_lower)
        if loc_match:
            location = loc_match.group(1).upper()

    budget  = DEFAULT_BUDGET
    numbers = re.findall(r'\b\d{3,5}\b', text_lower)
    if numbers:
        budget = int(numbers[0])

    time_pref = "flexible"
    if any(k in text_lower for k in ["urgent","jaldi","fori","abbi","now"]):
        time_pref = "urgent"

    return {
        "serviceType":          service_type,
        "location":             location,
        "budget":               budget,
        "time":                 time_pref,
        "confidence":           1.0,
        "confirmation_needed":  False,
        "confirmation_question":None,
        "detected_language":    "heuristic_fallback"
    }


