async def classify_intent(text: str) -> dict:
    """
    Lightweight intent classifier. Uses fast heuristic check first,
    then falls back to Gemini for ambiguous cases.
    Returns: {"intent": "greeting" | "service_request", "greeting_response": str | None}
    """
    cleaned = text.strip().lower()
    # Remove punctuation for matching
    import re
    cleaned_alpha = re.sub(r'[^\w\s]', '', cleaned)

    # ─── Fast Heuristic: exact/near-exact match on known greetings ────────
    if cleaned_alpha in _GREETING_PATTERNS or len(cleaned_alpha) <= 3:
        # Very short inputs or exact greeting matches → classify immediately
        # (len <= 3 catches "hi", "hy", "hey", "yo", "ok", "aoa", etc.)
        if cleaned_alpha in {"ok", "okay", "hmm", "achha", "alright"}:
            return {
                "intent": "greeting",
                "greeting_response": "Ji bilkul! Aap batayein, kaunsi service chahiye? (e.g. Plumber, Electrician, AC Technician)"
            }
        return {
            "intent": "greeting",
            "greeting_response": None  # Will be generated by Gemini below
        }

    # ─── Check if any service keywords are present → skip LLM call ────────
    service_keywords = [
        "plumber", "electrician", "ac", "painter", "carpenter", "tutor",
        "cleaning", "nurse", "nursing", "physio", "doctor", "telehealth",
        "nalka", "pipe", "paani", "leak", "toti",
        "bijli", "wiring", "current", "board", "short", "button",
        "cooling", "thanda", "fridge", "compressor",
        "rang", "paint", "deewar", "wallpaper",
        "barhai", "wood", "furniture", "door",
        "safai", "jharoo", "pocha",
        "repair", "fix", "install", "service", "kaam", "karo",
        "chahiye", "chahye", "bhejo", "bulao", "book",
    ]
    if any(kw in cleaned for kw in service_keywords):
        return {"intent": "service_request", "greeting_response": None}

    # ─── Ambiguous input: Use Gemini for classification ───────────────────
    try:
        prompt = f"""You are an intent classifier for KaamGraph, a Pakistani gig marketplace.
Classify this user message into exactly ONE of two categories:
1. "greeting" — casual greeting, hello, thanks, bye, how are you, small talk
2. "service_request" — any request for a service, worker, or tradesperson

User message: "{text}"

Return ONLY raw JSON, no markdown:
{{"intent": "greeting" or "service_request"}}"""
        response = await _model.generate_content_async(prompt)
        raw = response.text.strip()
        start = raw.find("{")
        end = raw.rfind("}") + 1
        if start != -1 and end > 0:
            result = json.loads(raw[start:end])
            return {
                "intent": result.get("intent", "service_request"),
                "greeting_response": None
            }
    except Exception as exc:
        print(f"[IntentClassifier] Gemini classification failed: {exc}")

    # Default: treat as service request (never block real queries)
    return {"intent": "service_request", "greeting_response": None}


